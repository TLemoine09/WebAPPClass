let cats = Number(prompt("How many cats do you have?"));
if (cats >= 3) {
    console.log("You have a lot of cats!");
} 

let dogs = Number(prompt("How many dogs do you have?"));
if (dogs >= 2) {
    console.log("You have a lot of dogs!");
}

if (cats >= 3 && dogs >= 2) {
    console.log("You have a lot of pets!");
}

